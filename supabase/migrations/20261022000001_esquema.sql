-- =============================================================================
-- SIN&AT — Sistema de Inteligencia de Negocios y Alerta Temprana
-- Restaurante Vila Baleia (Porto Moniz, Madeira)
--
-- Migración 1: esquema base. Exactamente 10 tablas.
--   perfil, proveedor, insumo, lote, movimiento, entrega,
--   comanda, regla, hecho, alerta
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 1. perfil — extiende auth.users con nombre y rol
-- -----------------------------------------------------------------------------
create table public.perfil (
  id         uuid primary key references auth.users (id) on delete cascade,
  nombre     text not null check (length(trim(nombre)) > 0),
  rol        text not null default 'operativo'
             check (rol in ('gerente', 'operativo')),
  creado_en  timestamptz not null default now()
);

comment on table public.perfil is 'Perfil de usuario y rol de acceso (gerente | operativo).';

-- -----------------------------------------------------------------------------
-- 2. proveedor
-- -----------------------------------------------------------------------------
create table public.proveedor (
  id              bigint generated by default as identity primary key,
  nombre          text not null unique check (length(trim(nombre)) > 0),
  lead_time_dias  integer not null check (lead_time_dias >= 0),
  contacto        text,
  activo          boolean not null default true
);

comment on column public.proveedor.lead_time_dias is 'Días entre hacer el pedido y recibirlo.';

-- -----------------------------------------------------------------------------
-- 3. insumo
-- -----------------------------------------------------------------------------
create table public.insumo (
  id                     bigint generated by default as identity primary key,
  nombre                 text not null unique check (length(trim(nombre)) > 0),
  unidad                 text not null check (unidad in ('kg', 'l', 'ud')),
  categoria              text not null,
  proveedor_id           bigint references public.proveedor (id) on delete restrict,
  dias_alerta_caducidad  integer not null default 2 check (dias_alerta_caducidad >= 0),
  vida_util_dias         integer not null check (vida_util_dias > 0),
  stock_minimo           numeric(12,3) not null default 0 check (stock_minimo >= 0),
  activo                 boolean not null default true
);

comment on column public.insumo.proveedor_id is 'Proveedor habitual del insumo (usado por R4).';
comment on column public.insumo.dias_alerta_caducidad is 'R1 se dispara cuando a un lote le quedan estos días o menos.';
comment on column public.insumo.vida_util_dias is 'R5: sobrestock si la cobertura supera 2 × este valor.';

-- -----------------------------------------------------------------------------
-- 4. lote — cada recepción de mercancía
-- -----------------------------------------------------------------------------
create table public.lote (
  id                bigint generated by default as identity primary key,
  insumo_id         bigint not null references public.insumo (id) on delete restrict,
  proveedor_id      bigint references public.proveedor (id) on delete restrict,
  cantidad_inicial  numeric(12,3) not null check (cantidad_inicial > 0),
  cantidad_actual   numeric(12,3) not null check (cantidad_actual >= 0),
  fecha_recepcion   date not null default current_date,
  fecha_caducidad   date not null,
  costo_unitario    numeric(10,2) not null default 0 check (costo_unitario >= 0),
  constraint lote_cantidad_actual_max check (cantidad_actual <= cantidad_inicial),
  constraint lote_fechas check (fecha_caducidad >= fecha_recepcion)
);

comment on column public.lote.cantidad_actual is 'Existencia viva del lote; se descuenta con CONSUMO y MERMA.';

-- -----------------------------------------------------------------------------
-- 5. movimiento — libro de entradas, consumos y mermas
-- -----------------------------------------------------------------------------
create table public.movimiento (
  id          bigint generated by default as identity primary key,
  insumo_id   bigint not null references public.insumo (id) on delete restrict,
  lote_id     bigint references public.lote (id) on delete restrict,
  tipo        text not null check (tipo in ('ENTRADA', 'CONSUMO', 'MERMA')),
  cantidad    numeric(12,3) not null check (cantidad > 0),
  motivo      text,
  fecha       timestamptz not null default now(),
  usuario_id  uuid references public.perfil (id) on delete set null default auth.uid(),
  -- Toda merma debe explicar por qué se perdió el producto.
  constraint movimiento_merma_con_motivo
    check (tipo <> 'MERMA' or length(trim(coalesce(motivo, ''))) > 0)
);

-- -----------------------------------------------------------------------------
-- 6. entrega — base del indicador de cumplimiento de proveedores (R3)
-- -----------------------------------------------------------------------------
create table public.entrega (
  id              bigint generated by default as identity primary key,
  proveedor_id    bigint not null references public.proveedor (id) on delete restrict,
  fecha_esperada  date not null,
  fecha_real      date,
  conforme        boolean,
  -- Sólo se califica la conformidad cuando la entrega ya llegó.
  constraint entrega_conforme_al_llegar
    check (fecha_real is not null or conforme is null)
);

comment on column public.entrega.fecha_real is 'NULL mientras la entrega está pendiente.';
comment on column public.entrega.conforme is 'Cantidad y calidad correctas. NULL mientras no ha llegado.';

-- -----------------------------------------------------------------------------
-- 7. comanda — tres marcas de tiempo del servicio
-- -----------------------------------------------------------------------------
create table public.comanda (
  id          bigint generated by default as identity primary key,
  mesa        text not null check (length(trim(mesa)) > 0),
  comensales  integer not null check (comensales > 0),
  t_apertura  timestamptz not null default now(),
  t_listo     timestamptz,
  t_cierre    timestamptz,
  usuario_id  uuid references public.perfil (id) on delete set null default auth.uid(),
  constraint comanda_listo_tras_apertura check (t_listo is null or t_listo >= t_apertura),
  constraint comanda_cierre_tras_listo
    check (t_cierre is null or (t_listo is not null and t_cierre >= t_listo))
);

-- -----------------------------------------------------------------------------
-- 8. regla — catálogo de reglas del motor de inferencia
-- -----------------------------------------------------------------------------
create table public.regla (
  id                     bigint generated by default as identity primary key,
  codigo                 text not null unique,
  nombre                 text not null,
  tipo                   text not null check (tipo in ('BASE', 'ENCADENADA')),
  umbral                 numeric(12,3),
  severidad_base         text not null check (severidad_base in ('BAJA', 'MEDIA', 'ALTA')),
  ventana_supresion_min  integer not null default 1440 check (ventana_supresion_min >= 0),
  activa                 boolean not null default true
);

comment on column public.regla.tipo is 'BASE evalúa datos; ENCADENADA evalúa hechos deducidos por otras reglas.';
comment on column public.regla.ventana_supresion_min is 'Minutos durante los que no se repite la misma alerta para la misma entidad.';

-- -----------------------------------------------------------------------------
-- 9. hecho — memoria de trabajo del motor (hechos deducidos)
-- -----------------------------------------------------------------------------
create table public.hecho (
  id            bigint generated by default as identity primary key,
  predicado     text not null check (predicado in (
                  'riesgo_caducidad', 'riesgo_faltante',
                  'proveedor_no_confiable', 'sobrestock')),
  entidad_tipo  text not null check (entidad_tipo in ('lote', 'insumo', 'proveedor')),
  entidad_id    bigint not null,
  vigente       boolean not null default true,
  creado_en     timestamptz not null default now()
);

comment on table public.hecho is 'Hechos afirmados por las reglas BASE y consumidos por las ENCADENADAS.';

-- -----------------------------------------------------------------------------
-- 10. alerta
-- -----------------------------------------------------------------------------
create table public.alerta (
  id             bigint generated by default as identity primary key,
  regla_id       bigint not null references public.regla (id) on delete restrict,
  tipo           text not null,
  entidad_tipo   text not null check (entidad_tipo in ('lote', 'insumo', 'proveedor', 'comanda')),
  entidad_id     bigint not null,
  valor          numeric(14,3),
  umbral         numeric(14,3),
  severidad      text not null check (severidad in ('BAJA', 'MEDIA', 'ALTA')),
  estado         text not null default 'ABIERTA'
                 check (estado in ('ABIERTA', 'ATENDIDA', 'SUPRIMIDA')),
  mensaje        text not null,
  creada_en      timestamptz not null default now(),
  atendida_por   uuid references public.perfil (id) on delete set null,
  atendida_en    timestamptz,
  accion_tomada  text,
  -- Una alerta atendida siempre registra quién, cuándo y qué se hizo.
  constraint alerta_atencion_completa check (
    estado <> 'ATENDIDA' or (
      atendida_por is not null
      and atendida_en is not null
      and length(trim(coalesce(accion_tomada, ''))) > 0))
);

-- =============================================================================
-- Índices
-- =============================================================================
create index insumo_proveedor_idx       on public.insumo (proveedor_id);

create index lote_insumo_idx            on public.lote (insumo_id);
create index lote_proveedor_idx         on public.lote (proveedor_id);
-- Lotes con existencia, ordenables por caducidad (R1, FEFO).
create index lote_vivos_caducidad_idx   on public.lote (fecha_caducidad)
  where cantidad_actual > 0;

create index movimiento_insumo_fecha_idx on public.movimiento (insumo_id, fecha desc);
create index movimiento_lote_idx         on public.movimiento (lote_id);
create index movimiento_usuario_idx      on public.movimiento (usuario_id);

create index entrega_proveedor_idx      on public.entrega (proveedor_id, fecha_esperada desc);

create index comanda_apertura_idx       on public.comanda (t_apertura desc);
create index comanda_usuario_idx        on public.comanda (usuario_id);

-- Un mismo hecho sólo puede estar vigente una vez (lo usa el ciclo de punto fijo).
create unique index hecho_vigente_uidx  on public.hecho (predicado, entidad_tipo, entidad_id)
  where vigente;

-- Bandeja de alertas abiertas y supresión de duplicados.
create index alerta_estado_idx          on public.alerta (estado, creada_en desc);
create index alerta_supresion_idx       on public.alerta (regla_id, entidad_tipo, entidad_id, creada_en desc);
create index alerta_regla_idx           on public.alerta (regla_id);
create index alerta_atendida_por_idx    on public.alerta (atendida_por);
